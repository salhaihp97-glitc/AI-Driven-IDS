def _menu_status(container: Container) -> None:
    from config.settings import get_settings
    from capture.live_capture_service import get_live_capture_service

    settings = get_settings()
    models = container.model_repository.get_all()
    active_models = [m for m in models if m.is_active]
    alerts = container.alert_repository.get_recent(limit=100)
    active_alerts = [a for a in alerts if not a.is_acknowledged]
    live_service = get_live_capture_service()
    cap = live_service.status

    _heading("System Status")
    print(f"  Version        : {_APP_VERSION}")
    print(f"  Environment    : {settings.app_env}")
    print(f"  Python         : {platform.python_version()}")
    print(f"  Platform       : {platform.system()} {platform.release()}")
    print(f"  Database       : {settings.database_path}")
    print(f"  Models Dir     : {settings.models_dir}")
    print(f"  Log Level      : {settings.log_level}")
    print(_SUB)
    print(f"  Models total   : {len(models)} ({len(active_models)} active)")
    print(f"  Alerts active  : {len(active_alerts)}")
    print(f"  Capture active : {cap.get('is_running', False)}")
    if cap.get("is_running"):
        print(f"  Capture pkts   : {cap.get('packet_count', 0)}")
        print(f"  Capture flows  : {cap.get('active_flows', 0)}")
    tg = "configured" if settings.telegram_bot_token else "not configured"
    print(f"  Telegram       : {tg}")
    print(_DIV)



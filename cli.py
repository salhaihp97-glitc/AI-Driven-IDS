def cmd_analyze_csv_scripted(container, model_id, file_path, max_rows):
    path = Path(file_path.strip().strip("\"'"))
    if not path.exists():
        print(f"Error: File not found: {path}", file=sys.stderr)
        return 1
    _resolve_model_id(container, model_id)
    summary = container.csv_analysis_service.analyze(model_id=model_id, csv_path=str(path), max_rows=max_rows)
    ratio = (summary.attack_count / summary.total_rows * 100) if summary.total_rows else 0.0
    print(f"Total: {summary.total_rows} | Normal: {summary.normal_count} | Attacks: {summary.attack_count} | Threat: {ratio:.2f}%")
    return 0


def cmd_analyze_pcap_scripted(container, model_id, file_path):
    path = Path(file_path.strip().strip("\"'"))
    if not path.exists():
        print(f"Error: File not found: {path}", file=sys.stderr)
        return 1
    _resolve_model_id(container, model_id)
    summary = container.pcap_analysis_service.analyze(model_id=model_id, pcap_path=str(path))
    print(f"Flows: {summary.total_flows} | Threats: {summary.attack_count} | Normal: {summary.normal_count}")
    return 0


def cmd_live_capture_scripted(container, model_id, interface, packets):
    from capture.live_capture_service import get_live_capture_service
    _, model_name = _resolve_model_id(container, model_id)
    live = get_live_capture_service()
    live.start(interface=interface or "", model_id=model_id, model_name=model_name)
    print(f"Live capture running (max {packets} packets). Ctrl+C to stop.")
    try:
        count = 0
        while live.status.get("is_running", False):
            st = live.status
            count = st.get("packet_count", 0)
            print(f"\r  Packets: {count:>8}  Flows: {st.get('active_flows', 0):>6}", end="", flush=True)
            time.sleep(1.0)
            if count >= packets:
                break
    except KeyboardInterrupt:
        pass
    print("\nCapture stopped.")
    return 0



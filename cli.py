def _heading(title: str) -> None:
    print(f"\n{_DIV}")
    print(f"  {title}")
    print(_DIV)


def _subheading(title: str) -> None:
    print(f"\n  {title}")
    print(f"  {_SUB}")


def _prompt(message: str, default: str = "") -> str:
    hint = f" [{default}]" if default else ""
    value = input(f"  {message}{hint}: ").strip()
    return value if value else default


def _confirm(message: str, default: bool = True) -> bool:
    hint = "Y/n" if default else "y/N"
    value = input(f"  {message} [{hint}]: ").strip().lower()
    if not value:
        return default
    return value in ("y", "yes")


def _env_exists() -> bool:
    return _ENV_PATH.exists()


def _detect_os() -> str:
    name = platform.system()
    if name == "Windows":
        return "Windows"
    elif name == "Linux":
        return "Linux"
    elif name == "Darwin":
        return "macOS"
    return name


def _detect_python() -> str:
    return platform.python_version()


def _read_env() -> dict[str, str]:
    result: dict[str, str] = {}
    if not _ENV_PATH.exists():
        return result
    for line in _ENV_PATH.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" in line:
            key, _, value = line.partition("=")
            key = key.strip()
            value = value.strip().strip('"').strip("'")
            result[key] = value
    return result


def _write_env(values: dict[str, str]) -> None:
    lines = [
        "# ==============================================================================",
        "# AI-IDS — Generated Environment Configuration",
        f"# Generated by Setup Wizard v{_APP_VERSION}",
        "# WARNING: Do not commit this file to version control.",
        "# ==============================================================================",
        "",
    ]

    sections = [
        ("# --- Environment & Debug ---", [
            "AI_IDS_ENV", "AI_IDS_DEBUG", "AI_IDS_SECRET_KEY",
        ]),
        ("# --- Paths ---", [
            "AI_IDS_DB_PATH", "AI_IDS_MODELS_DIR", "AI_IDS_LOGS_DIR",
            "AI_IDS_CAPTURED_FLOWS_DIR",
        ]),
        ("# --- Logging ---", [
            "AI_IDS_LOG_LEVEL", "AI_IDS_LOG_TO_CONSOLE",
            "AI_IDS_LOG_MAX_BYTES", "AI_IDS_LOG_BACKUP_COUNT",
        ]),
        ("# --- Security ---", [
            "AI_IDS_BCRYPT_ROUNDS",
        ]),
        ("# --- Alert Engine ---", [
            "AI_IDS_ALERT_WINDOW_MINUTES",
        ]),
        ("# --- Network Capture ---", [
            "AI_IDS_FLOW_IDLE_TIMEOUT", "AI_IDS_MONITORING_INTERVAL",
            "AI_IDS_CICFLOWMETER_INTERVAL_SECONDS",
            "AI_IDS_LIVE_CAPTURE_MODE", "AI_IDS_FLOW_EXTRACTOR",
        ]),
        ("# --- Telegram Notifications ---", [
            "AI_IDS_TELEGRAM_BOT_TOKEN", "AI_IDS_TELEGRAM_CHAT_ID",
        ]),
    ]

    for section_comment, keys in sections:
        lines.append(section_comment)
        for key in keys:
            val = values.get(key, DEFAULT_ENV_VARS.get(key, ""))
            if key in ("AI_IDS_TELEGRAM_BOT_TOKEN", "AI_IDS_TELEGRAM_CHAT_ID", "AI_IDS_SECRET_KEY"):
                if val:
                    lines.append(f'{key}="{val}"')
                else:
                    lines.append(f'{key}=""')
            else:
                lines.append(f"{key}={val}")
        lines.append("")

    _ENV_PATH.write_text("\n".join(lines), encoding="utf-8")


def _get_executable() -> str:
    return sys.executable


def _ensure_config_dirs(values: dict[str, str]) -> None:
    """
    Creates the operational directories referenced by the wizard's configured
    path values. Relative paths are anchored to the project root.
    """
    for key, is_file in (
        ("AI_IDS_DB_PATH", True),
        ("AI_IDS_MODELS_DIR", False),
        ("AI_IDS_LOGS_DIR", False),
        ("AI_IDS_CAPTURED_FLOWS_DIR", False),
    ):
        target = Path(values.get(key, DEFAULT_ENV_VARS.get(key, "")))
        if not target.is_absolute():
            target = _BASE_DIR / target
        (target.parent if is_file else target).mkdir(parents=True, exist_ok=True)



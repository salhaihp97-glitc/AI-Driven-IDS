def _show_banner() -> None:
    os_name = _detect_os()
    py_ver = _detect_python()
    env_label = "configured" if _env_exists() else "NOT configured"
    print(f"\n{'AI-IDS — Intrusion Detection System':^62}")
    print(f"{f'v{_APP_VERSION}  |  {os_name}  |  Python {py_ver}':^62}")
    print(f"{f'Config: {env_label}':^62}")
    print(_DIV)


def _show_menu() -> None:
    print()
    for key, (_, desc) in _MENU_ITEMS.items():
        label = key.rjust(3)
        print(f"  [{label}]  {desc}")
    print()
    max_key = max(int(k) for k in _MENU_ITEMS.keys())
    choice = input(f"  Select [0-{max_key}]: ").strip()
    return choice


def _main_menu() -> None:
    from services.container import get_container

    while True:
        _show_banner()
        choice = _show_menu()

        if choice == "0":
            print("\n  Session terminated. Goodbye.\n")
            break

        handler = _MENU_ITEMS.get(choice, (None, None))[0]
        if handler is None:
            print("  Invalid selection.")
            continue

        # Handlers that don't need the container
        if handler == "setup":
            run_setup_wizard()
            continue
        if handler == "launch-ui":
            cmd_launch_streamlit()
            continue

        # All other handlers need the container
        try:
            container = get_container()
        except Exception as exc:
            print(f"\n  ERROR: Failed to initialize system: {exc}")
            print("  Try running the Setup Wizard first (option 1).\n")
            input("  Press Enter to continue...")
            continue

        if handler == "status":
            _menu_status(container)
        elif handler == "list-models":
            _menu_list_models(container)
        elif handler == "analyze-csv":
            _menu_csv(container)
        elif handler == "analyze-pcap":
            _menu_pcap(container)
        elif handler == "live-capture":
            _menu_live(container)
        elif handler == "predict":
            _menu_predict(container)
        elif handler == "alerts":
            _menu_alerts(container)
        elif handler == "logs":
            _menu_logs(container)
        elif handler == "whitelist":
            _menu_whitelist(container)
        elif handler == "blacklist":
            _menu_blacklist(container)
        elif handler == "test-telegram":
            _menu_test_telegram(container)
        elif handler == "list-interfaces":
            _menu_interfaces()

        input("\n  Press Enter to continue...")



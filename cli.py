def _menu_csv(container: Container) -> None:
    _heading("Batch CSV Traffic Analysis")
    mid = _prompt("Model ID")
    fpath = _prompt("CSV file path")
    rows = _prompt("Max rows (Enter = unlimited)", "")

    if not mid.isdigit():
        print("  ERROR: Model ID must be a number.")
        return
    model_id = int(mid)

    path = Path(fpath.strip().strip("\"'"))
    if not path.exists():
        print(f"  ERROR: File not found: {path}")
        return

    print(f"\n  Analyzing {path.name} with model {model_id}...")
    try:
        summary = container.csv_analysis_service.analyze(
            model_id=model_id,
            csv_path=str(path),
            max_rows=int(rows) if rows.isdigit() else None,
        )
    except Exception as exc:
        print(f"  ERROR: {exc}")
        return

    ratio = (summary.attack_count / summary.total_rows * 100) if summary.total_rows else 0.0
    print(_DIV)
    print(f"  Total Rows Evaluated : {summary.total_rows}")
    print(f"  Normal Traffic       : {summary.normal_count}")
    print(f"  Malicious Anomalies  : {summary.attack_count}")
    print(f"  Threat Density       : {ratio:.2f}%")
    print(_DIV)



def cmd_launch_streamlit() -> None:
    """Launch the Streamlit web UI as a subprocess."""
    _heading("Launching AI-IDS Web Interface")
    app_path = _BASE_DIR / "app.py"
    if not app_path.exists():
        print("  ERROR: app.py not found in project root.")
        return

    print("  Starting Streamlit server...")
    print(f"  The browser will open automatically at {_STREAMLIT_URL}")
    print("  Press Ctrl+C in this terminal to stop the server.\n")

    try:
        process = subprocess.Popen(
            [sys.executable, "-m", "streamlit", "run", str(app_path),
             "--server.headless", "false",
             "--browser.gatherUsageStats", "false"],
            cwd=str(_BASE_DIR),
        )
        process.wait()
    except KeyboardInterrupt:
        print("\n  Streamlit server stopped.")
        process.terminate()



def main() -> None:
    """Main entry point."""
    _ensure_utf8()

    parser = _build_parser()
    args = parser.parse_args()

    # No command → launch interactive menu (auto-detect first run)
    if not args.command:
        if not _env_exists():
            _heading("Welcome to AI-IDS")
            print("  No configuration file detected.")
            print("  Let's set up your system.\n")
            if _confirm("  Start Setup Wizard now?", default=True):
                if run_setup_wizard():
                    print("  Setup complete! Launching operations console...\n")
                else:
                    print("  Setup was not completed. You can run it later with: python cli.py setup\n")
        _main_menu()
        sys.exit(0)

    # Scripted commands
    cmd = args.command
    if cmd == "setup":
        run_setup_wizard()
    elif cmd == "launch":
        cmd_launch_streamlit()
    else:
        from services.container import get_container
        try:
            container = get_container()
        except Exception as exc:
            print(f"Error: Failed to initialize system: {exc}", file=sys.stderr)
            sys.exit(1)

        dispatch = {
            "status":           lambda: _menu_status(container),
            "list-models":      lambda: _menu_list_models(container),
            "list-interfaces":  lambda: _menu_interfaces(),
            "analyze-csv":      lambda: cmd_analyze_csv_scripted(container, args.model_id, args.file, args.max_rows),
            "analyze-pcap":     lambda: cmd_analyze_pcap_scripted(container, args.model_id, args.file),
            "live-capture":     lambda: cmd_live_capture_scripted(container, args.model_id, args.interface, args.packets),
            "predict":          lambda: cmd_predict_scripted(container, args.model_id, args.data, args.src_ip, args.dst_ip),
            "alerts":           lambda: cmd_alerts_scripted(container, args.limit),
        }
        handler = dispatch.get(cmd)
        if handler:
            try:
                exit_code = handler()
            except (ValueError, RuntimeError) as exc:
                print(f"Error: {exc}", file=sys.stderr)
                sys.exit(1)
            sys.exit(exit_code or 0)
        parser.print_help()



def run_setup_wizard() -> bool:
    """Interactive setup wizard. Returns True if completed successfully."""

    _heading("AI-IDS Setup Wizard")
    print("  This wizard will guide you through the initial configuration.")
    print("  Press Enter to accept the default value shown in [brackets].\n")

    values: dict[str, str] = dict(DEFAULT_ENV_VARS)

    # Load existing .env if present
    if _env_exists():
        existing = _read_env()
        values.update(existing)
        print("  Existing .env configuration detected. Defaults updated.\n")

    # ── Step 1: Operating System ──────────────────────────────────────
    _subheading(f"Step 1/{_SETUP_STEPS}: Operating System Detection")
    os_name = _detect_os()
    print(f"  Detected OS : {os_name}")
    print(f"  Python      : {_detect_python()}")
    print(f"  Architecture: {platform.machine()}")
    if not _confirm("  Is this correct?"):
        print("  Please ensure you are running the correct Python version for your OS.")
        return False

    # ── Step 2: Install Dependencies ──────────────────────────────────
    _subheading(f"Step 2/{_SETUP_STEPS}: Install Dependencies")
    req_path = _BASE_DIR / "requirements.txt"
    if not req_path.exists():
        print("  WARNING: requirements.txt not found. Skipping dependency installation.")
    else:
        if _confirm("  Install Python packages from requirements.txt?", default=True):
            print("  Running: pip install -r requirements.txt ...")
            python = _get_executable()
            try:
                result = subprocess.run(
                    [python, "-m", "pip", "install", "-r", str(req_path), "--quiet"],
                    capture_output=True, text=True, timeout=_PIP_INSTALL_TIMEOUT_SECONDS,
                )
                if result.returncode == 0:
                    print("  Dependencies installed successfully.")
                else:
                    print(f"  WARNING: pip returned exit code {result.returncode}")
                    if result.stderr:
                        for line in result.stderr.strip().splitlines()[-5:]:
                            print(f"    {line}")
                    if not _confirm("  Continue anyway?", default=True):
                        return False
            except subprocess.TimeoutExpired:
                print(
                    "  WARNING: pip install timed out "
                    f"({_PIP_INSTALL_TIMEOUT_SECONDS // 60} min limit). Continuing..."
                )
            except FileNotFoundError:
                print("  ERROR: pip not found. Please install dependencies manually.")
                if not _confirm("  Continue anyway?", default=False):
                    return False

    # ── Step 3: Paths ─────────────────────────────────────────────────
    _subheading(f"Step 3/{_SETUP_STEPS}: Directory Paths")
    values["AI_IDS_DB_PATH"] = _prompt("Database file path", values["AI_IDS_DB_PATH"])
    values["AI_IDS_MODELS_DIR"] = _prompt("Models directory", values["AI_IDS_MODELS_DIR"])
    values["AI_IDS_LOGS_DIR"] = _prompt("Logs directory", values["AI_IDS_LOGS_DIR"])
    values["AI_IDS_CAPTURED_FLOWS_DIR"] = _prompt(
        "Captured flows directory", values["AI_IDS_CAPTURED_FLOWS_DIR"]
    )

    # Ensure the configured directories exist (anchored to project root)
    _ensure_config_dirs(values)
    print("  Directories verified/created.")

    # ── Step 4: Security ──────────────────────────────────────────────
    _subheading(f"Step 4/{_SETUP_STEPS}: Security Settings")
    env_choice = _prompt(
        "Environment (1=Development, 2=Production)",
        "1" if values["AI_IDS_ENV"] == "development" else "2",
    )
    values["AI_IDS_ENV"] = "production" if env_choice == "2" else "development"

    values["AI_IDS_DEBUG"] = "true" if values["AI_IDS_ENV"] == "development" else "false"

    if values["AI_IDS_SECRET_KEY"] in (INSECURE_SECRET_KEY, ""):
        values["AI_IDS_SECRET_KEY"] = secrets.token_hex(32)
        print("  Secret key generated automatically.")
    else:
        if _confirm("  Generate a new secret key?", default=False):
            values["AI_IDS_SECRET_KEY"] = secrets.token_hex(32)
            print("  New secret key generated.")

    values["AI_IDS_BCRYPT_ROUNDS"] = _prompt("Bcrypt hash rounds", values["AI_IDS_BCRYPT_ROUNDS"])

    # ── Step 5: Telegram (optional) ───────────────────────────────────
    _subheading(f"Step 5/{_SETUP_STEPS}: Telegram Notifications (Optional)")
    if _confirm("  Enable Telegram threat notifications?", default=False):
        values["AI_IDS_TELEGRAM_BOT_TOKEN"] = _prompt(
            "Bot Token", values["AI_IDS_TELEGRAM_BOT_TOKEN"]
        )
        values["AI_IDS_TELEGRAM_CHAT_ID"] = _prompt(
            "Chat ID", values["AI_IDS_TELEGRAM_CHAT_ID"]
        )

        if values["AI_IDS_TELEGRAM_BOT_TOKEN"] and values["AI_IDS_TELEGRAM_CHAT_ID"]:
            if _confirm("  Test Telegram connection now?", default=True):
                _test_telegram(values["AI_IDS_TELEGRAM_BOT_TOKEN"], values["AI_IDS_TELEGRAM_CHAT_ID"])
    else:
        values["AI_IDS_TELEGRAM_BOT_TOKEN"] = ""
        values["AI_IDS_TELEGRAM_CHAT_ID"] = ""

    # ── Step 6: Network Capture ───────────────────────────────────────
    _subheading(f"Step 6/{_SETUP_STEPS}: Network Capture Settings")
    live_choice = _prompt(
        "Live capture engine (1=Native, 2=CICFlowMeter)",
        "1" if values["AI_IDS_LIVE_CAPTURE_MODE"] == "native" else "2",
    )
    values["AI_IDS_LIVE_CAPTURE_MODE"] = "cicflowmeter" if live_choice == "2" else "native"

    ext_choice = _prompt(
        "Offline flow extractor (1=Native, 2=CICFlowMeter)",
        "1" if values["AI_IDS_FLOW_EXTRACTOR"] == "native" else "2",
    )
    values["AI_IDS_FLOW_EXTRACTOR"] = "cicflowmeter" if ext_choice == "2" else "native"

    values["AI_IDS_FLOW_IDLE_TIMEOUT"] = _prompt(
        "Flow idle timeout (seconds)", values["AI_IDS_FLOW_IDLE_TIMEOUT"]
    )
    values["AI_IDS_MONITORING_INTERVAL"] = _prompt(
        "Monitoring poll interval (seconds)", values["AI_IDS_MONITORING_INTERVAL"]
    )
    values["AI_IDS_CICFLOWMETER_INTERVAL_SECONDS"] = _prompt(
        "CICFlowMeter flush interval (seconds)", values["AI_IDS_CICFLOWMETER_INTERVAL_SECONDS"]
    )
    values["AI_IDS_ALERT_WINDOW_MINUTES"] = _prompt(
        "Alert aggregation window (minutes)", values["AI_IDS_ALERT_WINDOW_MINUTES"]
    )

    # ── Step 7: Save ──────────────────────────────────────────────────
    _subheading(f"Step 7/{_SETUP_STEPS}: Save Configuration")
    _heading("Configuration Summary")
    print(f"  Environment   : {values['AI_IDS_ENV']}")
    print(f"  Database      : {values['AI_IDS_DB_PATH']}")
    print(f"  Models dir    : {values['AI_IDS_MODELS_DIR']}")
    print(f"  Logs dir      : {values['AI_IDS_LOGS_DIR']}")
    print(f"  Log level     : {values['AI_IDS_LOG_LEVEL']}")
    print(f"  Bcrypt rounds : {values['AI_IDS_BCRYPT_ROUNDS']}")
    print(f"  Flow extractor: {values['AI_IDS_FLOW_EXTRACTOR']}")
    tg_status = "configured" if values.get("AI_IDS_TELEGRAM_BOT_TOKEN") else "not configured"
    print(f"  Telegram      : {tg_status}")
    print()

    if not _confirm("  Save this configuration?", default=True):
        print("  Setup cancelled. No changes saved.")
        return False

    _write_env(values)
    print(f"\n  Configuration saved to: {_ENV_PATH}")
    print("  IMPORTANT: Restart the application for changes to take effect.\n")

    return True


def _test_telegram(token: str, chat_id: str) -> None:
    print("  Testing Telegram connection...")
    try:
        from infrastructure.notifications.telegram_notifier import TelegramNotifier
        notifier = TelegramNotifier(bot_token=token, chat_id=chat_id)
        ok = notifier.send_test_alert()
        if ok:
            print("  Telegram test message sent successfully!")
        else:
            print("  Telegram test failed. Check your Bot Token and Chat ID.")
    except Exception as exc:
        print(f"  Telegram test error: {exc}")


